import type { NextConfig } from "next";

/**
 * بناءان من مصدر واحد:
 *
 * * **الويب** (الافتراضي) — كما كان، بلا تغيير.
 * * **سطح المكتب** (`GOVMIND_DESKTOP=1`) — تصدير ساكن إلى `out/` يخدمه
 *   GovMind Runtime من جهاز العميل. ممكن لأن كل صفحات التطبيق صفحات عميل:
 *   لا مسارات API ولا middleware ولا أي ميزة خادم.
 *
 * **النتيجة: لا Node.js على جهاز العميل.** لو احتجنا `next start` لاحتاج
 * كل عميل تثبيت Node، وهو ما يمنعه الشرط صراحة.
 *
 * ----------------------------------------------------------------------
 * ⚠️ **شجرتا مسارات لا شجرة واحدة** — وهذا ما يمنع عودة العطل
 * ----------------------------------------------------------------------
 * `pageExtensions` في بناء سطح المكتب مقصورة على `desktop.tsx`، فلا يرى
 * Next من `app/` إلا `layout.desktop.tsx` و`page.desktop.tsx`. النتيجة أن
 * التصدير المثبَّت على جهاز العميل:
 *
 * * **لا يحتوي `/login/`** — فلا نموذج دخول ثانٍ يمكن أن يُعرض، ولا طلب
 *   `POST /api/auth/login` يمكن أن يُرسل، وهو الطلب الذي كان يعود بـ405.
 * * **لا يحتوي `/admin/` ولا `/settings/`** — فلا يدخل حزمةَ العميل أي
 *   نصّ عن جهة أو مسؤول أو دور، ولا حقلَ «رابط السيرفر».
 *
 * إخفاء تلك الصفحات بشرط في الشيفرة كان سيبقي نصوصها في الحزمة المصدَّرة
 * ويجعل الشرط وعدًا لا يمكن فحصه. أمّا ألّا تُبنى فهو أمر يفحصه اختبار
 * بمجرد قراءة مخرجات البناء.
 */
const isDesktop = process.env.GOVMIND_DESKTOP === "1";

const nextConfig: NextConfig = {
  // لا نحتاج توليد AGENTS.md و CLAUDE.md تلقائيًا داخل frontend/.
  agentRules: false,

  ...(isDesktop
    ? {
        output: "export" as const,
        // ملفات تُفتح من الـRuntime بمسارات مجلدات — `/settings/` لا
        // `/settings.html`. هذا ما يخدمه `StaticFiles(html=True)`.
        trailingSlash: true,
        // لا مُحسِّن صور: يحتاج خادم Node، ولا وجود له على جهاز العميل.
        images: { unoptimized: true },
        // ⚠️ الشرط الذي يقصر التصدير على تطبيق العميل — انظر أعلاه.
        pageExtensions: ["desktop.tsx"],
      }
    : {}),
};

export default nextConfig;
